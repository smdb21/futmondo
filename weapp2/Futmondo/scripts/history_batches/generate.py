"""Generate the operational batched alternative to the atomic history migration.
Run from the application root. No production connection or credentials used.
"""
from pathlib import Path
import re
source=Path('scripts/migrations/20261118200000_normalize_fact_histories.sql').read_text()
specs=[('price','player_history','player_id,championship_id,competition_id,season','value,change,points,avg_points,avg_last_five,matches'),('match','player_match_observations','player_id,championship_id,competition_id,season,scoring_version,round,source_round_key','points,score_status,is_home,minutes_raw,start_raw,participation,round_id,match_id,source_round_number,occurred_at,round_start_at'),('finance','rival_finance_evidence','account_id,championship_id,competition_id,season,evidence_type,source_id','payload')]
blocks=re.split(r'(?=-- Normalize repeated historical facts:)',source)[1:]
for (pre,table,keys,facts),old in zip(specs,blocks):
 def array(s): return 'ARRAY['+','.join("'"+x+"'" for x in s.split(','))+']'
 def protect(name,access): return f'ALTER TABLE public.{name} ENABLE ROW LEVEL SECURITY;\nREVOKE ALL ON public.{name} FROM PUBLIC,anon,authenticated;\nGRANT {access} ON public.{name} TO service_role;\n'
 ddl='\n'.join(l for l in old.splitlines() if (l.startswith('CREATE TABLE public.') or l.startswith('CREATE INDEX ') or l.startswith('CREATE UNIQUE INDEX ')))+'\n'
 setup=f'''-- Generated by scripts/history_batches/generate.py. Prepare {pre} without replacing source data.
BEGIN;
SET LOCAL lock_timeout='5s';
SET LOCAL statement_timeout='30s';
{ddl}
CREATE TABLE public.{pre}_migration_status(id boolean PRIMARY KEY DEFAULT true CHECK(id),seeded boolean NOT NULL DEFAULT false,seed_cursor jsonb,completed_at timestamptz);
INSERT INTO public.{pre}_migration_status DEFAULT VALUES;
CREATE TABLE public.{pre}_migration_queue(entity_id bigint PRIMARY KEY REFERENCES public.{pre}_history_entities ON DELETE CASCADE);
CREATE TABLE public.{pre}_migration_verified(entity_id bigint PRIMARY KEY REFERENCES public.{pre}_history_entities ON DELETE CASCADE,source_rows bigint NOT NULL,endpoint_rows bigint NOT NULL,verified_at timestamptz NOT NULL);
'''
 for kind in ['entities','states','times']:setup+=protect(f'{pre}_history_{kind}','SELECT,INSERT,UPDATE,DELETE')
 for kind in ['status','queue','verified']:setup+=protect(f'{pre}_migration_{kind}','SELECT,INSERT,UPDATE,DELETE')
 for kind in ['entities','states']:setup+=f'GRANT USAGE,SELECT ON SEQUENCE public.{pre}_history_{kind}_{"entity" if kind=="entities" else "state"}_id_seq TO service_role;\n'
 view=old[old.index('DO $$ DECLARE columns text;'):old.index('CREATE FUNCTION public.')]
 view=view[:view.index(' IF EXISTS')]+ 'END $$;\n'
 view=view.replace(f'{table}_legacy',table).replace(f'CREATE VIEW public.{table}',f'CREATE VIEW public.{pre}_history_preview')
 setup+=view+f'REVOKE ALL ON public.{pre}_history_preview FROM PUBLIC,anon,authenticated;\nGRANT SELECT ON public.{pre}_history_preview TO service_role;\n'
 lookup=' AND '.join(f'e.{k} IS NOT DISTINCT FROM r.{k}' for k in keys.split(','))
 setup+=f'''CREATE FUNCTION public.{pre}_migration_changed() RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path=public,pg_temp AS $$
DECLARE item jsonb;r public.{table}; v_entity bigint;
BEGIN
 IF TG_OP='TRUNCATE' THEN RAISE EXCEPTION 'History migration in progress; TRUNCATE is disabled'; END IF;
 FOR item IN SELECT value FROM jsonb_array_elements(CASE TG_OP WHEN 'INSERT' THEN jsonb_build_array(to_jsonb(NEW)) WHEN 'DELETE' THEN jsonb_build_array(to_jsonb(OLD)) ELSE jsonb_build_array(to_jsonb(OLD),to_jsonb(NEW)) END) LOOP
 r:=jsonb_populate_record(NULL::public.{table},item);
 -- Deletes never recreate an entity removed by a parent FK cascade.
 SELECT entity_id INTO v_entity FROM public.{pre}_history_entities e WHERE {lookup};
 IF v_entity IS NULL AND TG_OP<>'DELETE' THEN
 INSERT INTO public.{pre}_history_entities({keys}) VALUES({','.join('r.'+k for k in keys.split(','))}) ON CONFLICT DO NOTHING;
 SELECT entity_id INTO v_entity FROM public.{pre}_history_entities e WHERE {lookup};
 END IF;
 IF v_entity IS NOT NULL THEN
 INSERT INTO public.{pre}_migration_queue VALUES(v_entity) ON CONFLICT(entity_id) DO UPDATE SET entity_id=excluded.entity_id;
 DELETE FROM public.{pre}_migration_verified WHERE entity_id=v_entity;
 END IF;
 END LOOP;
 RETURN NULL;
END $$;
REVOKE ALL ON FUNCTION public.{pre}_migration_changed() FROM PUBLIC,anon,authenticated;
CREATE TRIGGER history_migration_changed AFTER INSERT OR UPDATE OR DELETE ON public.{table} FOR EACH ROW EXECUTE FUNCTION public.{pre}_migration_changed();
CREATE TRIGGER history_migration_no_truncate BEFORE TRUNCATE ON public.{table} FOR EACH STATEMENT EXECUTE FUNCTION public.{pre}_migration_changed();
'''
 cursor_keys='id' if pre=='price' else keys+',observed_at'
 page_keys=keys+(',id' if pre=='price' else ',observed_at')
 join=' AND '.join(f'e.{k} {"IS NOT DISTINCT FROM" if pre=="price" else "="} o.{k}' for k in keys.split(','))
 if pre=='price':join+=' AND md5(jsonb_build_array('+','.join('e.'+k for k in keys.split(','))+')::text)=md5(jsonb_build_array('+','.join('o.'+k for k in keys.split(','))+')::text)'
 setup+=f"""CREATE FUNCTION public.{pre}_migration_seed(p_limit integer DEFAULT 10000) RETURNS bigint LANGUAGE plpgsql SECURITY INVOKER SET search_path=public,pg_temp AS $$
DECLARE n bigint;cursor_value jsonb;predicate text:='true';
BEGIN
 IF p_limit IS NULL OR p_limit<1 OR p_limit>20000 THEN RAISE EXCEPTION 'Invalid discovery page size'; END IF;
 PERFORM 1 FROM public.{pre}_migration_status WHERE id FOR UPDATE;
 IF (SELECT seeded FROM public.{pre}_migration_status WHERE id) THEN RETURN 0; END IF;
 SELECT seed_cursor INTO cursor_value FROM public.{pre}_migration_status WHERE id;
 IF cursor_value IS NOT NULL THEN
 SELECT '({cursor_keys}) > ('||string_agg(quote_literal(cursor_value->>k),',' ORDER BY ord)||')' INTO predicate FROM unnest({array(cursor_keys)}) WITH ORDINALITY AS cols(k,ord);
 END IF;
 CREATE TEMP TABLE IF NOT EXISTS {pre}_seed_page ON COMMIT DROP AS SELECT {page_keys} FROM public.{table} WITH NO DATA;
 TRUNCATE pg_temp.{pre}_seed_page;
 EXECUTE 'INSERT INTO pg_temp.{pre}_seed_page SELECT {page_keys} FROM public.{table} WHERE '||predicate||' ORDER BY {cursor_keys} LIMIT '||p_limit;
 GET DIAGNOSTICS n=ROW_COUNT;
 INSERT INTO public.{pre}_history_entities({keys}) SELECT DISTINCT {keys} FROM pg_temp.{pre}_seed_page ON CONFLICT DO NOTHING;
 INSERT INTO public.{pre}_migration_queue SELECT e.entity_id FROM (SELECT DISTINCT {keys} FROM pg_temp.{pre}_seed_page) o JOIN public.{pre}_history_entities e ON {join} ON CONFLICT DO NOTHING;
 IF n>0 THEN SELECT to_jsonb(o) INTO cursor_value FROM pg_temp.{pre}_seed_page o ORDER BY {','.join(k+' DESC' for k in cursor_keys.split(','))} LIMIT 1; END IF;
 UPDATE public.{pre}_migration_status SET seed_cursor=cursor_value,seeded=n<p_limit WHERE id;
 RETURN n;
END $$;
REVOKE ALL ON FUNCTION public.{pre}_migration_seed(integer) FROM PUBLIC,anon,authenticated,service_role;
"""

 order='observed_at'+(',recorded_at,id' if pre=='price' else '')
 uncertain='observed_at IS NULL OR NOT isfinite(observed_at)'+(' OR player_id IS NULL OR championship_id IS NULL' if pre=='price' else '')
 sig='md5(jsonb_build_array('+','.join('o.'+x for x in facts.split(','))+')::text)'
 equality=' AND '.join(f's.{x} IS NOT DISTINCT FROM o.{x}' for x in facts.split(','))
 cached_sig='o._migration_signature'
 timescols='id,observed_at,recorded_at,source_unique' if pre=='price' else 'observed_at'
 timesexpr='o.id,o.observed_at,o.recorded_at,o.player_id IS NOT NULL AND o.championship_id IS NOT NULL' if pre=='price' else 'o.observed_at'
 setup+=f'''CREATE FUNCTION public.{pre}_migration_batch(p_limit integer DEFAULT 25,p_budget_ms integer DEFAULT 5000) RETURNS jsonb
LANGUAGE plpgsql SECURITY INVOKER SET search_path=public,pg_temp AS $$
DECLARE job record;identity jsonb;predicate text;started timestamptz:=clock_timestamp();n integer:=0;src bigint;dst bigint;mismatch boolean;
BEGIN
 IF p_limit<1 OR p_limit>200 OR p_limit IS NULL OR p_budget_ms<1 OR p_budget_ms>20000 OR p_budget_ms IS NULL THEN RAISE EXCEPTION 'Invalid batch bounds'; END IF;
 IF NOT (SELECT seeded AND completed_at IS NULL FROM public.{pre}_migration_status WHERE id) THEN RAISE EXCEPTION 'Migration is not ready for batches'; END IF;
 -- Match cutover lock order and prevent cutover while a batch is active.
 LOCK TABLE public.{table} IN ACCESS SHARE MODE;
 CREATE TEMP TABLE IF NOT EXISTS {pre}_batch_source ON COMMIT DROP AS SELECT * FROM public.{table} WITH NO DATA;
 CREATE TEMP TABLE IF NOT EXISTS {pre}_batch_retained ON COMMIT DROP AS SELECT o.*,NULL::text AS _migration_signature FROM public.{table} o WITH NO DATA;
 FOR job IN SELECT entity_id FROM public.{pre}_migration_queue ORDER BY entity_id LIMIT p_limit FOR UPDATE SKIP LOCKED LOOP
 SELECT to_jsonb(e) INTO identity FROM public.{pre}_history_entities e WHERE entity_id=job.entity_id;
 IF identity IS NULL THEN CONTINUE; END IF;
 SELECT string_agg(format('%I',k)||CASE WHEN identity->>k IS NULL THEN ' IS NULL' ELSE '='||quote_literal(identity->>k) END,' AND ') INTO predicate FROM unnest({array(keys)}) k;
 TRUNCATE pg_temp.{pre}_batch_source,pg_temp.{pre}_batch_retained;
 EXECUTE 'INSERT INTO pg_temp.{pre}_batch_source SELECT * FROM public.{table} WHERE '||predicate;
 GET DIAGNOSTICS src=ROW_COUNT;
 INSERT INTO pg_temp.{pre}_batch_retained SELECT (original).*,NULL::text FROM (
 SELECT o AS original,({uncertain}) AS uncertain,ROW({facts}) AS fact,
 lag(ROW({facts})) OVER w AS preceding,lead(ROW({facts})) OVER w AS following
 FROM pg_temp.{pre}_batch_source o WINDOW w AS (ORDER BY {order})
 ) periods WHERE uncertain OR fact IS DISTINCT FROM preceding OR fact IS DISTINCT FROM following;
 GET DIAGNOSTICS dst=ROW_COUNT;
 UPDATE pg_temp.{pre}_batch_retained o SET _migration_signature={sig};
 ANALYZE pg_temp.{pre}_batch_retained(_migration_signature);
 DELETE FROM public.{pre}_history_times WHERE entity_id=job.entity_id;
 DELETE FROM public.{pre}_history_states WHERE entity_id=job.entity_id;
 INSERT INTO public.{pre}_history_states(entity_id,signature,{facts}) SELECT DISTINCT job.entity_id,{cached_sig},{','.join('o.'+x for x in facts.split(','))} FROM pg_temp.{pre}_batch_retained o;
 INSERT INTO public.{pre}_history_times(entity_id,state_id,{timescols}) SELECT job.entity_id,s.state_id,{timesexpr} FROM pg_temp.{pre}_batch_retained o JOIN public.{pre}_history_states s ON s.entity_id=job.entity_id AND s.signature={cached_sig} AND {equality};
 -- Full retained-row equality, including IDs, nulls, payloads and timestamp precision.
 EXECUTE 'SELECT EXISTS((SELECT to_jsonb(o)-''_migration_signature'' FROM pg_temp.{pre}_batch_retained o EXCEPT ALL SELECT to_jsonb(v) FROM public.{pre}_history_preview v WHERE '||predicate||') UNION ALL (SELECT to_jsonb(v) FROM public.{pre}_history_preview v WHERE '||predicate||' EXCEPT ALL SELECT to_jsonb(o)-''_migration_signature'' FROM pg_temp.{pre}_batch_retained o))' INTO mismatch;
 IF mismatch THEN RAISE EXCEPTION 'Retained history verification failed'; END IF;
 INSERT INTO public.{pre}_migration_verified VALUES(job.entity_id,src,dst,clock_timestamp()) ON CONFLICT(entity_id) DO UPDATE SET source_rows=excluded.source_rows,endpoint_rows=excluded.endpoint_rows,verified_at=excluded.verified_at;
 DELETE FROM public.{pre}_migration_queue WHERE entity_id=job.entity_id;
 n:=n+1;
 EXIT WHEN extract(epoch FROM clock_timestamp()-started)*1000>=p_budget_ms;
 END LOOP;
 RETURN jsonb_build_object('processed',n,'pending',(SELECT count(*) FROM public.{pre}_migration_queue),'verified',(SELECT count(*) FROM public.{pre}_migration_verified));
END $$;
REVOKE ALL ON FUNCTION public.{pre}_migration_batch(integer,integer) FROM PUBLIC,anon,authenticated,service_role;
COMMIT;
'''
 Path(f'scripts/history_batches/prepare_{pre}.sql').write_text(setup)
 writer=old[old.index(f'CREATE FUNCTION public.{pre}_history_write'):old.index(f'ALTER TABLE public.{pre}_history_entities ENABLE')]
 routing=old[old.index('CREATE OR REPLACE FUNCTION public.worker_write_fact'):old.index(f'ANALYZE public.{pre}_history_entities;',old.index('CREATE OR REPLACE FUNCTION public.worker_write_fact'))]
 latest=''
 if pre!='price':
  viewname='player_round_points_latest' if pre=='match' else 'rival_finance_evidence_latest'
  a=old.index(f'CREATE OR REPLACE VIEW public.{viewname}');latest=old[a:old.index(';',a)+1]+'\n'
 cut=f'''-- Generated by scripts/history_batches/generate.py. Switch only fully verified {pre} histories.
BEGIN;
SET LOCAL lock_timeout='5s';
SET LOCAL statement_timeout='30s';
LOCK TABLE public.{table} IN ACCESS EXCLUSIVE MODE;
DO $$ BEGIN
 IF NOT (SELECT seeded AND completed_at IS NULL FROM public.{pre}_migration_status WHERE id) THEN RAISE EXCEPTION 'Migration not ready'; END IF;
 IF EXISTS(SELECT 1 FROM public.{pre}_migration_queue) OR EXISTS(SELECT 1 FROM public.{pre}_history_entities e LEFT JOIN public.{pre}_migration_verified v USING(entity_id) WHERE v.entity_id IS NULL) THEN RAISE EXCEPTION 'Pending or unverified histories; resume batches'; END IF;
END $$;
DROP TRIGGER history_migration_changed ON public.{table};
DROP TRIGGER history_migration_no_truncate ON public.{table};
DROP FUNCTION public.{pre}_migration_changed();
DROP FUNCTION public.{pre}_migration_seed(integer);
DROP FUNCTION public.{pre}_migration_batch(integer,integer);
ALTER TABLE public.{table} RENAME TO {table}_legacy;
ALTER VIEW public.{pre}_history_preview RENAME TO {table};
'''
 if pre=='price':cut+='ALTER SEQUENCE public.player_history_id_seq OWNED BY public.price_history_times.id;\n'
 cut+=writer+latest+routing+f'DROP TABLE public.{table}_legacy;\nUPDATE public.{pre}_migration_status SET completed_at=clock_timestamp() WHERE id;\n'
 for kind in ['entities','states','times']:cut+=f'ANALYZE public.{pre}_history_{kind};\n'
 cut+="NOTIFY pgrst,'reload schema';\nCOMMIT;\n"
 Path(f'scripts/history_batches/cutover_{pre}.sql').write_text(cut)
